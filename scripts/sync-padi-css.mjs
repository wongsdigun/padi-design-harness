#!/usr/bin/env node
/* scripts/sync-padi-css.mjs
 * Synchronize and isolate PaDi DS CSS tokens and component styles strictly under .padi-theme
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';

const padiDsPath = resolve(process.cwd(), '../frontend-shared/packages/padi-ds');
const distCssPath = resolve(padiDsPath, 'dist/styles.css');
const varCssPath = resolve(padiDsPath, 'src/styles/variables.css');
const textCssPath = resolve(padiDsPath, 'src/styles/text-styles.css');

if (!existsSync(distCssPath) && !existsSync(varCssPath)) {
  console.error(`[sync-padi-css] Error: Cannot find padi-ds at ${padiDsPath}`);
  process.exit(1);
}

console.log('[sync-padi-css] Reading PaDi DS CSS tokens...');
let varCss = readFileSync(varCssPath, 'utf8');
let textCss = readFileSync(textCssPath, 'utf8');

// Scope all top-level selectors in variables.css under .padi-theme
let scopedVariables = varCss
  .replace(/:root\s*\{/g, '.padi-theme {')
  .replace(/\[data-theme="brand-red"\]\s*\{/g, '.padi-theme[data-theme="brand-red"], .padi-theme [data-theme="brand-red"] {')
  .replace(/\[data-theme="brand-orange"\]\s*\{/g, '.padi-theme[data-theme="brand-orange"], .padi-theme [data-theme="brand-orange"] {')
  .replace(/\[data-mode-button="primary"\]\s*\{/g, '.padi-theme [data-mode-button="primary"] {')
  .replace(/\[data-mode-button="tertiery"\],\s*\[data-mode-button="secondary"\]\s*\{/g, '.padi-theme [data-mode-button="tertiery"], .padi-theme [data-mode-button="secondary"] {')
  .replace(/\[data-mode-button="destructive"\]\s*\{/g, '.padi-theme [data-mode-button="destructive"] {')
  .replace(/\[data-mode-mimin="default"\]\s*\{/g, '.padi-theme [data-mode-mimin="default"] {')
  .replace(/\[data-mode-mimin="active"\]\s*\{/g, '.padi-theme [data-mode-mimin="active"] {')
  .replace(/\[data-mode-anchor-text="default"\]\s*\{/g, '.padi-theme [data-mode-anchor-text="default"] {')
  .replace(/\[data-mode-anchor-text="inactive"\]\s*\{/g, '.padi-theme [data-mode-anchor-text="inactive"] {');

// Component CSS inlined from dist/
const distCss = readFileSync(distCssPath, 'utf8');
const importMatches = [...distCss.matchAll(/@import\s+['"]\.\/components\/([^'"]+)['"];/g)];
let inlinedComponentCss = '';

for (const match of importMatches) {
  const relFile = join('components', match[1]);
  const fullPath = resolve(padiDsPath, 'dist', relFile);
  if (existsSync(fullPath)) {
    inlinedComponentCss += `\n/* Component: ${relFile} */\n` + readFileSync(fullPath, 'utf8') + '\n';
  } else {
    console.warn(`[sync-padi-css] Warning: Component CSS not found: ${fullPath}`);
  }
}

// Rename keyframes to conform to Design Studio requirement: ${themeClass}-*
let processedComponentCss = inlinedComponentCss
  .replace(/@keyframes\s+ds-spinner-rotate\s*\{/g, '@keyframes padi-theme-spinner-rotate {')
  .replace(/ds-spinner-rotate/g, 'padi-theme-spinner-rotate')
  .replace(/@keyframes\s+ds-btn-spin\s*\{/g, '@keyframes padi-theme-btn-spin {')
  .replace(/ds-btn-spin/g, 'padi-theme-btn-spin');

// Extract top-level keyframe definitions so they sit outside .padi-theme { ... }
const keyframeBlocks = [];
processedComponentCss = processedComponentCss.replace(/@keyframes\s+padi-theme-[^{]+\{(?:[^{}]*\{[^{}]*\}[^{}]*)*\}/g, (match) => {
  keyframeBlocks.push(match);
  return '';
});

const finalThemeCss = `/* ==========================================================================
   PaDi UMKM Design System Theme (Generated by scripts/sync-padi-css.mjs)
   Source: @frontend-shared/padi-ds v1.0.3
   Theme Class: padi-theme
   ========================================================================== */

/* Scoped Keyframes */
${keyframeBlocks.join('\n\n')}

/* Scoped PaDi CSS Custom Properties */
${scopedVariables}

/* Scoped Typography, Text Styles & Components */
.padi-theme {
  font-family: var(--font-family-sans, 'Ubuntu', sans-serif);
  color: var(--neutral-900, #1A1A1A);
  background-color: var(--neutral-25, #FCFCFD);

  ${textCss}

  ${processedComponentCss}
}
`;

const targetPath = resolve(process.cwd(), 'src/systems/padi/styles/theme.css');
writeFileSync(targetPath, finalThemeCss, 'utf8');
console.log(`[sync-padi-css] Successfully wrote scoped theme to ${targetPath} (${finalThemeCss.length} bytes, ${importMatches.length} components inlined)`);
